#!/usr/bin/env python3
"""Subset Material Symbols Outlined to the icons the web app uses.

The full variable font is ~4 MB. This keeps only the glyphs referenced in src/ (any string literal
that is a Material Symbols name), pins weight 400 / grade 0 / optical size 24, keeps the FILL axis,
and writes:
  src/fonts/material-symbols-subset.woff2
  src/components/ds/icon-codepoints.ts   (name -> code point, the type of <Icon name>)

Run after adding icons:  python3 apps/web/scripts/build-icon-font.py   (needs: pip install fonttools brotli)
"""
import pathlib, re, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools import subset

WEB = pathlib.Path(__file__).resolve().parents[1]
ROOT = WEB.parents[1]
SRC = WEB / "src"
FONT = next(p for p in [WEB / "node_modules/material-symbols/material-symbols-outlined.woff2",
                        ROOT / "node_modules/material-symbols/material-symbols-outlined.woff2"] if p.exists())

font = TTFont(FONT)
cmap = font.getBestCmap()
char_of = {}
for cp, g in sorted(cmap.items()):
    char_of.setdefault(g, cp)
pua = {g: cp for cp, g in cmap.items() if cp >= 0xE000}
# Icon names are GSUB ligatures (e.g. "location_on"); several names can share one glyph.
name_to_cp = {}
gsub = font["GSUB"].table
for lookup in gsub.LookupList.Lookup:
    for st in lookup.SubTable:
        if lookup.LookupType == 7:
            st = st.ExtSubTable
        for first, ligs in getattr(st, "ligatures", {}).items():
            for lig in ligs:
                name = "".join(chr(char_of[g]) for g in [first] + lig.Component).lower()
                if lig.LigGlyph in pua:
                    name_to_cp[name] = pua[lig.LigGlyph]
known = set(name_to_cp)

used = set()
pattern = re.compile(r"[\"'`]([a-z0-9_]{2,60})[\"'`]")
for path in SRC.rglob("*.ts*"):
    if path.name == "icon-codepoints.ts":
        continue
    for m in pattern.finditer(path.read_text(encoding="utf-8")):
        if m.group(1) in known:
            used.add(m.group(1))
used |= {"close", "check", "expand_more", "menu", "search", "notifications", "chevron_right", "chevron_left", "logout"}
names = sorted(used)
print(f"{len(names)} icons", file=sys.stderr)

import io
inst = instancer.instantiateVariableFont(TTFont(FONT, lazy=False), {"wght": 400, "GRAD": 0, "opsz": 24})
buf = io.BytesIO()
inst.flavor = None
inst.save(buf)
buf.seek(0)
inst = TTFont(buf, lazy=False)
opts = subset.Options()
opts.flavor = "woff2"
opts.layout_features = []
opts.name_IDs = ["*"]
opts.notdef_outline = True
sub = subset.Subsetter(opts)
sub.populate(unicodes=sorted({name_to_cp[n] for n in names}))
sub.subset(inst)
out = SRC / "fonts/material-symbols-subset.woff2"
out.parent.mkdir(parents=True, exist_ok=True)
inst.flavor = "woff2"
inst.save(out)
print(f"wrote {out} ({out.stat().st_size // 1024} KB)", file=sys.stderr)

lines = ["// Generated by scripts/build-icon-font.py. Do not edit by hand.",
         "export const ICON_CODEPOINTS = {"]
lines += [f'  "{n}": 0x{name_to_cp[n]:x},' for n in names]
lines += ["} as const;", "", "export type IconName = keyof typeof ICON_CODEPOINTS;", ""]
(SRC / "components/ds/icon-codepoints.ts").write_text("\n".join(lines), encoding="utf-8")
