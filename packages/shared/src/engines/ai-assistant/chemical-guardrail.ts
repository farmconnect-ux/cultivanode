import type { GuardrailCheckResult } from './types';
import { APPROVED_CHEMICALS_REGISTRY } from '../inputs/spray-planner';

const BANNED_CHEMICAL_NAMES = ['paraquat', 'carbofuran', 'ddt', 'endosulfan', 'lindane', 'monocrotophos', 'aldrin'];

/** Words that show a sentence is warning against a product rather than recommending it (English, Pidgin, Yorùbá). */
const WARNING_CONTEXT =
  /\b(ban(ned|s)?|prohibit(ed|s)?|illegal|outlawed|withdrawn|never|avoid|do not|don't|dont|must not|should not|shouldn't|not (be )?used?|not recommended|no longer|instead of|unsafe|toxic|dangerous|hazard(ous)?|fofinde|ma(ṣ|s)e lo|no use am|make you no)\b/i;

/**
 * Validates text generated by an AI model against Nigerian agrochemical safety regulations.
 * Enforces strict blocking of banned pesticides and attaches mandatory PHI/REI safety warnings.
 */
export function checkChemicalSafetyGuardrails(responseText: string): GuardrailCheckResult {
  const lower = responseText.toLowerCase();
  const bannedDetected: string[] = [];
  const approvedDetected: string[] = [];
  const safetyAppendices: string[] = [];
  const unsafe: string[] = [];
  const sentences = lower.split(/(?<=[.!?;:\n])\s+|\n+/);
  for (const banned of BANNED_CHEMICAL_NAMES) {
    const hits = sentences.filter((sentence) => sentence.split(/[^a-z0-9]+/).includes(banned));
    if (!hits.length) continue;
    bannedDetected.push(banned);
    // Any occurrence is blocked, including quotations, warnings and educational discussion.
    unsafe.push(banned);
  }

  for (const chemical of APPROVED_CHEMICALS_REGISTRY) {
    if (!chemical.isBannedInNigeria) {
      const activeMatch = lower.includes(chemical.activeIngredient.toLowerCase());
      const brandMatch = lower.includes(chemical.brandName.toLowerCase().split(' ')[0]!.toLowerCase());
      if (activeMatch || brandMatch) {
        approvedDetected.push(chemical.brandName);
        safetyAppendices.push(
          `[MANDATORY SAFETY NOTICE: ${chemical.brandName}] Pre-Harvest Interval (PHI): ${chemical.preHarvestIntervalDays} days. Re-Entry Interval (REI): ${chemical.reEntryIntervalHours} hours. Recommended rate: ${chemical.recommendedRateLitersOrKgPerHa} L or kg/ha.`
        );
      }
    }
  }

  if (unsafe.length > 0) {
    return {
      passed: false,
      bannedChemicalsDetected: bannedDetected,
      approvedChemicalsDetected: approvedDetected,
      safetyAppendices: [],
      sanitizedResponseText: `SAFETY BLOCK: This response mentions a pesticide prohibited for agricultural use in Nigeria (${unsafe.join(', ')}). Do not use or apply it. Consult an agricultural extension officer for safe, approved alternatives.`,
    };
  }

  let sanitized = responseText;
  if (safetyAppendices.length > 0) sanitized = `${responseText}\n\n---\n${safetyAppendices.join('\n')}`;
  return {
    passed: true,
    bannedChemicalsDetected: bannedDetected,
    approvedChemicalsDetected: approvedDetected,
    safetyAppendices,
    sanitizedResponseText: sanitized,
  };
}
